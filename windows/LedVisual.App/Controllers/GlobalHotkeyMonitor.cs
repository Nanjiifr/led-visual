using System.Runtime.InteropServices;
using LedVisual.Core.Models;
using LedVisual.Core.Services;

namespace LedVisual.App.Controllers;

/// <summary>
/// Global low-level keyboard hook (WH_KEYBOARD_LL) that supports:
/// - Modifier + key combos (e.g. Alt+Space, Ctrl+Shift+A)
/// - Single keys without modifiers (e.g. F8)
/// - Standalone modifier keys (e.g. Right Alt, Right Ctrl, Right Win)
/// Distinguishes short tap (instant screenshot) vs press-and-hold (screen recording).
/// Must be created and started on the UI thread with an active WinForms message loop.
/// </summary>
public sealed class GlobalHotkeyMonitor : IDisposable
{
    private const int WhKeyboardLl = 13;
    private const int WmKeyDown = 0x0100;
    private const int WmKeyUp = 0x0101;
    private const int WmSysKeyDown = 0x0104;
    private const int WmSysKeyUp = 0x0105;

    private delegate nint LowLevelKeyboardProc(int nCode, nint wParam, nint lParam);

    private readonly LowLevelKeyboardProc _hookCallback;
    private readonly System.Windows.Forms.Timer _holdTimer;

    private nint _hookHandle;
    private Hotkey _hotkey;
    private int _holdThresholdMs;
    private bool _swallowEvents;
    private bool _isSuspended;
    private bool _disposed;

    // Press tracking state
    private bool _isKeyCurrentlyDown;
    private bool _isHoldActive;
    private bool _modifierInterruptedByOtherKey;

    public event Action? OnTap;
    public event Action? OnHoldStarted;
    public event Action? OnHoldEnded;

    public bool IsRunning => _hookHandle != nint.Zero;

    public bool IsSuspended
    {
        get => _isSuspended;
        set
        {
            if (_isSuspended == value)
            {
                return;
            }

            _isSuspended = value;
            if (_isSuspended)
            {
                CancelActivePress();
            }
        }
    }

    public GlobalHotkeyMonitor(
        Hotkey? hotkey = null,
        int holdThresholdMs = 350,
        bool swallowEvents = true)
    {
        _hotkey = hotkey ?? Hotkey.Default;
        _holdThresholdMs = Math.Max(150, holdThresholdMs);
        _swallowEvents = swallowEvents;
        _hookCallback = HookCallback;

        _holdTimer = new System.Windows.Forms.Timer
        {
            Interval = _holdThresholdMs
        };
        _holdTimer.Tick += HoldTimer_Tick;
    }

    public void UpdateConfiguration(Hotkey hotkey, int holdThresholdMs, bool swallowEvents)
    {
        CancelActivePress();
        _hotkey = hotkey;
        _holdThresholdMs = Math.Max(150, holdThresholdMs);
        _holdTimer.Interval = _holdThresholdMs;
        _swallowEvents = swallowEvents;
    }

    public bool Start()
    {
        ObjectDisposedException.ThrowIf(_disposed, this);

        if (_hookHandle != nint.Zero)
        {
            return true;
        }

        var moduleHandle = GetModuleHandle(null);
        _hookHandle = SetWindowsHookEx(WhKeyboardLl, _hookCallback, moduleHandle, 0);
        return _hookHandle != nint.Zero;
    }

    public void Stop()
    {
        CancelActivePress();

        if (_hookHandle != nint.Zero)
        {
            _ = UnhookWindowsHookEx(_hookHandle);
            _hookHandle = nint.Zero;
        }
    }

    public void Dispose()
    {
        if (_disposed)
        {
            return;
        }

        _disposed = true;
        Stop();
        _holdTimer.Tick -= HoldTimer_Tick;
        _holdTimer.Dispose();
    }

    private nint HookCallback(int nCode, nint wParam, nint lParam)
    {
        if (nCode >= 0 && !_isSuspended)
        {
            var msg = (int)wParam;
            var isKeyDown = msg is WmKeyDown or WmSysKeyDown;
            var isKeyUp = msg is WmKeyUp or WmSysKeyUp;

            if (isKeyDown || isKeyUp)
            {
                var info = Marshal.PtrToStructure<KBDLLHOOKSTRUCT>(lParam);
                var vkCode = (int)info.vkCode;

                // Ignore synthetic Caps Lock LED pulses generated by Win32CapsLockLedController
                if (vkCode == Hotkey.VkCapital && info.dwExtraInfo == Win32CapsLockLedController.InjectedExtraInfo)
                {
                    return CallNextHookEx(_hookHandle, nCode, wParam, lParam);
                }

                var shouldSwallow = _hotkey.Kind switch
                {
                    HotkeyKind.KeyCombo => HandleKeyComboEvent(vkCode, isKeyDown),
                    HotkeyKind.ModifierOnly => HandleModifierOnlyEvent(vkCode, isKeyDown),
                    _ => false
                };

                if (shouldSwallow)
                {
                    return (nint)1;
                }
            }
        }

        return CallNextHookEx(_hookHandle, nCode, wParam, lParam);
    }

    private bool HandleKeyComboEvent(int vkCode, bool isKeyDown)
    {
        if (isKeyDown)
        {
            if (_isKeyCurrentlyDown && vkCode == _hotkey.VirtualKeyCode)
            {
                // Filter auto-repeat while held down
                return _swallowEvents;
            }

            if (Hotkey.IsModifierKey(vkCode) || Hotkey.IsCapsLock(vkCode))
            {
                return false;
            }

            var currentModifiers = ReadCurrentModifiers();
            if (!_hotkey.MatchesKeyDown(vkCode, currentModifiers))
            {
                return false;
            }

            BeginPress();
            return _swallowEvents;
        }
        else
        {
            if (!_isKeyCurrentlyDown || vkCode != _hotkey.VirtualKeyCode)
            {
                return false;
            }

            EndPress();
            return _swallowEvents;
        }
    }

    private bool HandleModifierOnlyEvent(int vkCode, bool isKeyDown)
    {
        if (isKeyDown)
        {
            if (vkCode == _hotkey.VirtualKeyCode)
            {
                // Ignore auto-repeat while modifier is held
                if (_isKeyCurrentlyDown)
                {
                    return false;
                }

                var targetFlag = Hotkey.GetModifierFlag(vkCode);
                if (!targetFlag.HasValue)
                {
                    return false;
                }

                // Ensure no other standard modifiers are already held down
                var otherModifiers = ReadCurrentModifiers() & ~targetFlag.Value;
                if (otherModifiers == HotkeyModifiers.None)
                {
                    _modifierInterruptedByOtherKey = false;
                    BeginPress();
                }

                return false;
            }

            // If user presses another key while holding a standalone modifier (e.g. Right Alt + C),
            // treat it as a normal keyboard shortcut instead of firing LedVisual.
            if (_isKeyCurrentlyDown && !_isHoldActive)
            {
                _modifierInterruptedByOtherKey = true;
                CancelActivePress();
            }

            return false;
        }
        else
        {
            if (vkCode != _hotkey.VirtualKeyCode || !_isKeyCurrentlyDown)
            {
                return false;
            }

            if (!_modifierInterruptedByOtherKey)
            {
                EndPress();
            }
            else
            {
                CancelActivePress();
            }

            return false;
        }
    }

    private void BeginPress()
    {
        _isKeyCurrentlyDown = true;
        _isHoldActive = false;
        _holdTimer.Stop();
        _holdTimer.Interval = _holdThresholdMs;
        _holdTimer.Start();
    }

    private void HoldTimer_Tick(object? sender, EventArgs e)
    {
        _holdTimer.Stop();
        if (!_isKeyCurrentlyDown)
        {
            return;
        }

        _isHoldActive = true;
        OnHoldStarted?.Invoke();
    }

    private void EndPress()
    {
        _holdTimer.Stop();

        var wasHold = _isHoldActive;
        _isKeyCurrentlyDown = false;
        _isHoldActive = false;

        if (wasHold)
        {
            OnHoldEnded?.Invoke();
        }
        else
        {
            OnTap?.Invoke();
        }
    }

    private void CancelActivePress()
    {
        _holdTimer.Stop();
        var wasHold = _isHoldActive;
        _isKeyCurrentlyDown = false;
        _isHoldActive = false;

        if (wasHold)
        {
            OnHoldEnded?.Invoke();
        }
    }

    public static HotkeyModifiers ReadCurrentModifiers()
    {
        var mods = HotkeyModifiers.None;
        if (IsKeyPressed(Hotkey.VkControl) || IsKeyPressed(Hotkey.VkLControl) || IsKeyPressed(Hotkey.VkRControl))
        {
            mods |= HotkeyModifiers.Control;
        }

        if (IsKeyPressed(Hotkey.VkMenu) || IsKeyPressed(Hotkey.VkLMenu) || IsKeyPressed(Hotkey.VkRMenu))
        {
            mods |= HotkeyModifiers.Alt;
        }

        if (IsKeyPressed(Hotkey.VkShift) || IsKeyPressed(Hotkey.VkLShift) || IsKeyPressed(Hotkey.VkRShift))
        {
            mods |= HotkeyModifiers.Shift;
        }

        if (IsKeyPressed(Hotkey.VkLWin) || IsKeyPressed(Hotkey.VkRWin))
        {
            mods |= HotkeyModifiers.Win;
        }

        return mods;
    }

    private static bool IsKeyPressed(int vkCode) => (GetAsyncKeyState(vkCode) & 0x8000) != 0;

    [DllImport("user32.dll", SetLastError = true)]
    private static extern nint SetWindowsHookEx(int idHook, LowLevelKeyboardProc lpfn, nint hMod, uint dwThreadId);

    [DllImport("user32.dll", SetLastError = true)]
    [return: MarshalAs(UnmanagedType.Bool)]
    private static extern bool UnhookWindowsHookEx(nint hhk);

    [DllImport("user32.dll")]
    private static extern nint CallNextHookEx(nint hhk, int nCode, nint wParam, nint lParam);

    [DllImport("kernel32.dll", CharSet = CharSet.Unicode, SetLastError = true)]
    private static extern nint GetModuleHandle(string? lpModuleName);

    [DllImport("user32.dll")]
    private static extern short GetAsyncKeyState(int vKey);

    [StructLayout(LayoutKind.Sequential)]
    private struct KBDLLHOOKSTRUCT
    {
        public uint vkCode;
        public uint scanCode;
        public uint flags;
        public uint time;
        public nint dwExtraInfo;
    }
}
