using System.Runtime.InteropServices;
using LedVisual.Core.Models;

namespace LedVisual.Core.Services;

public readonly record struct BlinkStep(bool LedOn, int DurationMs);

public static class BlinkPatternBuilder
{
    /// <summary>
    /// Generates LED steps for one or more 1-based answers.
    /// - Single answer [3]: 3 short blinks, then stops (no trailing long blink).
    /// - Multi-select [1, 3]: 1 short blink, inter-answer pause, then 3 short blinks, then stops.
    /// </summary>
    public static IReadOnlyList<BlinkStep> StepsForAnswers(
        IEnumerable<int> answers,
        bool initiallyOn,
        BlinkTimings? timings = null)
    {
        var t = timings ?? BlinkTimings.Default;
        var validAnswers = answers.Where(a => a > 0).ToArray();
        if (validAnswers.Length == 0)
        {
            return [];
        }

        var steps = new List<BlinkStep>();

        if (initiallyOn)
        {
            steps.Add(new BlinkStep(false, t.PreBlinkDarkMs));
        }

        for (var groupIndex = 0; groupIndex < validAnswers.Length; groupIndex++)
        {
            var blinkCount = validAnswers[groupIndex];
            var isLastGroup = groupIndex == validAnswers.Length - 1;

            for (var blinkIndex = 0; blinkIndex < blinkCount; blinkIndex++)
            {
                var isLastBlinkInGroup = blinkIndex == blinkCount - 1;
                steps.Add(new BlinkStep(true, t.ShortOnMs));

                if (isLastBlinkInGroup && isLastGroup)
                {
                    steps.Add(new BlinkStep(false, initiallyOn ? t.PreBlinkDarkMs : 0));
                }
                else if (isLastBlinkInGroup)
                {
                    steps.Add(new BlinkStep(false, t.InterAnswerPauseMs));
                }
                else
                {
                    steps.Add(new BlinkStep(false, t.ShortOffMs));
                }
            }
        }

        return steps;
    }

    /// <summary>
    /// Generates a single long blink indicating a failed request or unparseable answer.
    /// </summary>
    public static IReadOnlyList<BlinkStep> StepsForError(
        bool initiallyOn,
        BlinkTimings? timings = null)
    {
        var t = timings ?? BlinkTimings.Default;
        var steps = new List<BlinkStep>(3);

        if (initiallyOn)
        {
            steps.Add(new BlinkStep(false, t.PreBlinkDarkMs));
        }

        steps.Add(new BlinkStep(true, t.ErrorLongOnMs));
        steps.Add(new BlinkStep(false, initiallyOn ? t.PreBlinkDarkMs : 0));
        return steps;
    }
}

public interface ICapsLockLedController
{
    bool GetState();
    void SetState(bool enabled);
}

/// <summary>
/// Controls the Windows Caps Lock LED via GetKeyState(VK_CAPITAL) and SendInput.
/// </summary>
public sealed class Win32CapsLockLedController : ICapsLockLedController
{
    private const ushort VkCapital = 0x14;
    private const uint InputKeyboard = 1;
    private const uint KeyEventFKeyUp = 0x0002;

    /// <summary>
    /// Marker tag placed in KEYBDINPUT.dwExtraInfo so global keyboard hooks can recognize
    /// synthetic Caps Lock toggles generated by LedVisual.
    /// </summary>
    public static readonly nint InjectedExtraInfo = new(0x4C454456); // "LEDV"

    private readonly object _toggleLock = new();

    public bool GetState()
    {
        return (GetKeyState(VkCapital) & 0x0001) != 0;
    }

    public void SetState(bool enabled)
    {
        lock (_toggleLock)
        {
            if (GetState() == enabled)
            {
                return;
            }

            var inputs = new INPUT[2];
            inputs[0].type = InputKeyboard;
            inputs[0].U.ki = new KEYBDINPUT
            {
                wVk = VkCapital,
                wScan = 0,
                dwFlags = 0,
                time = 0,
                dwExtraInfo = InjectedExtraInfo
            };

            inputs[1].type = InputKeyboard;
            inputs[1].U.ki = new KEYBDINPUT
            {
                wVk = VkCapital,
                wScan = 0,
                dwFlags = KeyEventFKeyUp,
                time = 0,
                dwExtraInfo = InjectedExtraInfo
            };

            _ = SendInput((uint)inputs.Length, inputs, Marshal.SizeOf<INPUT>());
        }
    }

    [DllImport("user32.dll")]
    private static extern short GetKeyState(int nVirtKey);

    [DllImport("user32.dll", SetLastError = true)]
    private static extern uint SendInput(uint nInputs, [In] INPUT[] pInputs, int cbSize);

    [StructLayout(LayoutKind.Sequential)]
    private struct INPUT
    {
        public uint type;
        public InputUnion U;
    }

    [StructLayout(LayoutKind.Explicit)]
    private struct InputUnion
    {
        [FieldOffset(0)] public MOUSEINPUT mi;
        [FieldOffset(0)] public KEYBDINPUT ki;
        [FieldOffset(0)] public HARDWAREINPUT hi;
    }

    [StructLayout(LayoutKind.Sequential)]
    private struct MOUSEINPUT
    {
        public int dx;
        public int dy;
        public uint mouseData;
        public uint dwFlags;
        public uint time;
        public nint dwExtraInfo;
    }

    [StructLayout(LayoutKind.Sequential)]
    private struct KEYBDINPUT
    {
        public ushort wVk;
        public ushort wScan;
        public uint dwFlags;
        public uint time;
        public nint dwExtraInfo;
    }

    [StructLayout(LayoutKind.Sequential)]
    private struct HARDWAREINPUT
    {
        public uint uMsg;
        public ushort wParamL;
        public ushort wParamH;
    }
}

public sealed class BlinkEngine
{
    public delegate Task Sleeper(int milliseconds, CancellationToken cancellationToken);

    private readonly ICapsLockLedController _controller;
    private readonly Sleeper _sleepMs;
    private readonly object _stateLock = new();

    private CancellationTokenSource? _activeCts;
    private bool? _savedOriginalState;

    public BlinkEngine(
        ICapsLockLedController? controller = null,
        Sleeper? sleepMs = null)
    {
        _controller = controller ?? new Win32CapsLockLedController();
        _sleepMs = sleepMs ?? DefaultSleepAsync;
    }

    public void Cancel()
    {
        CancellationTokenSource? ctsToCancel;
        bool? stateToRestore;

        lock (_stateLock)
        {
            ctsToCancel = _activeCts;
            _activeCts = null;
            stateToRestore = _savedOriginalState;
            _savedOriginalState = null;
        }

        if (ctsToCancel is not null)
        {
            try
            {
                ctsToCancel.Cancel();
            }
            catch (ObjectDisposedException)
            {
            }
        }

        if (stateToRestore.HasValue)
        {
            SafeSetState(stateToRestore.Value);
        }
    }

    public Task BlinkAnswersAsync(
        IEnumerable<int> answers,
        BlinkTimings? timings = null,
        CancellationToken cancellationToken = default)
    {
        var answerArray = answers.ToArray();
        var effectiveTimings = timings ?? BlinkTimings.Default;
        return RunSequenceAsync(
            initiallyOn => BlinkPatternBuilder.StepsForAnswers(answerArray, initiallyOn, effectiveTimings),
            cancellationToken);
    }

    public Task BlinkErrorAsync(
        BlinkTimings? timings = null,
        CancellationToken cancellationToken = default)
    {
        var effectiveTimings = timings ?? BlinkTimings.Default;
        return RunSequenceAsync(
            initiallyOn => BlinkPatternBuilder.StepsForError(initiallyOn, effectiveTimings),
            cancellationToken);
    }

    private async Task RunSequenceAsync(
        Func<bool, IReadOnlyList<BlinkStep>> buildSteps,
        CancellationToken externalCancellationToken)
    {
        Cancel();

        bool originalState;
        try
        {
            originalState = _controller.GetState();
        }
        catch
        {
            return;
        }

        var localCts = CancellationTokenSource.CreateLinkedTokenSource(externalCancellationToken);
        lock (_stateLock)
        {
            _activeCts = localCts;
            _savedOriginalState = originalState;
        }

        var steps = buildSteps(originalState);

        try
        {
            foreach (var step in steps)
            {
                if (localCts.Token.IsCancellationRequested)
                {
                    break;
                }

                SafeSetState(step.LedOn);

                if (step.DurationMs > 0)
                {
                    try
                    {
                        await _sleepMs(step.DurationMs, localCts.Token).ConfigureAwait(false);
                    }
                    catch (OperationCanceledException)
                    {
                        break;
                    }
                }
            }
        }
        finally
        {
            bool? stateToRestore = null;
            lock (_stateLock)
            {
                if (ReferenceEquals(_activeCts, localCts))
                {
                    _activeCts = null;
                    stateToRestore = _savedOriginalState;
                    _savedOriginalState = null;
                }
            }

            if (stateToRestore.HasValue)
            {
                SafeSetState(stateToRestore.Value);
            }

            localCts.Dispose();
        }
    }

    private void SafeSetState(bool enabled)
    {
        try
        {
            _controller.SetState(enabled);
        }
        catch
        {
        }
    }

    private static Task DefaultSleepAsync(int milliseconds, CancellationToken cancellationToken)
    {
        if (milliseconds <= 0)
        {
            return Task.CompletedTask;
        }

        return Task.Delay(milliseconds, cancellationToken);
    }
}
